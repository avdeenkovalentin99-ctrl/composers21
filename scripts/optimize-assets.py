"""Rebuild WOFF2 fonts and responsive images from preserved local originals.

Dependencies: python -m pip install --target .tmp-tools -r scripts/requirements-assets.txt
Run: python scripts/optimize-assets.py
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.tmp-tools'))
from PIL import Image, ImageOps, ImageCms
from io import BytesIO
from fontTools.ttLib import TTFont

config = json.loads((ROOT / 'scripts/asset-sources.json').read_text(encoding='utf-8'))
out = ROOT / 'public/assets/optimized'
out.mkdir(parents=True, exist_ok=True)
manifest = {}
summary = {'fonts': [], 'images': []}
for source in config['fonts']:
    file = ROOT / source
    font = TTFont(file)
    destination = ROOT / 'public/fonts' / (file.stem + '.woff2')
    font.flavor = 'woff2'
    font.save(destination)
    restored = TTFont(destination)
    assert font.getBestCmap() == restored.getBestCmap(), file
    assert font['hmtx'].metrics == restored['hmtx'].metrics, file
    summary['fonts'].append({'source': source, 'before': file.stat().st_size, 'after': destination.stat().st_size, 'glyphsAndMetricsPreserved': True})

images = dict(config['images'])
for file in sorted((ROOT / 'src/assets/participants').iterdir()):
    if file.suffix.lower() in {'.png', '.jpg', '.jpeg', '.jfif', '.webp'}:
        images['participants/' + file.name] = str(file.relative_to(ROOT)).replace('\\', '/')

for key, source in images.items():
    file = ROOT / source
    digest = hashlib.sha256(file.read_bytes()).hexdigest()[:16]
    with Image.open(file) as original:
        img = ImageOps.exif_transpose(original)
        has_alpha = 'A' in img.getbands() or 'transparency' in img.info
        alpha = img.convert('RGBA').getchannel('A') if has_alpha else None
        icc = img.info.get('icc_profile')
        if icc:
            profile = ImageCms.ImageCmsProfile(BytesIO(icc))
            mode = {'RGB': 'RGB', 'CMYK': 'CMYK', 'GRAY': 'L', 'Lab': 'LAB'}.get(profile.profile.xcolor_space.strip(), 'RGB')
            img = ImageCms.profileToProfile(img.convert(mode), profile, ImageCms.createProfile('sRGB'), outputMode='RGB')
        else:
            img = img.convert('RGB')
        if alpha is not None:
            img.putalpha(alpha)
        logo = key.startswith('brand/') or '/partners/' in key
        max_width = min(img.width, 660 if logo else 1440)
        widths = sorted({min(max_width, width) for width in ([190, 380, 660] if logo else [384, 768, 1440])})
        variants = []
        for width in widths:
            height = max(1, round(img.height * width / img.width))
            target = out / f'{digest}-{width}.webp'
            resized = img.resize((width, height), Image.Resampling.LANCZOS)
            if original.format == 'WEBP' and original.size == (width, height) and not icc and original.getexif().get(274, 1) == 1:
                # An already encoded WebP at its native size needs no new loss.
                target.write_bytes(file.read_bytes())
            else:
                resized.save(target, 'WEBP', quality=88, method=6, lossless=logo)
            variants.append({'src': '/assets/optimized/' + target.name, 'width': width, 'height': height, 'bytes': target.stat().st_size})
        largest = variants[-1]
        manifest[key] = {'src': largest['src'], 'srcSet': ', '.join(f"{item['src']} {item['width']}w" for item in variants), 'width': largest['width'], 'height': largest['height']}
        summary['images'].append({'key': key, 'source': source, 'before': file.stat().st_size, 'largestAfter': largest['bytes'], 'variants': variants})

destination = ROOT / 'src/app/data/optimizedImages.generated.ts'
destination.write_text('// Generated by scripts/optimize-assets.py. Do not edit manually.\n'
    + 'export type OptimizedImage = { src: string; srcSet: string; width: number; height: number };\n'
    + 'export const optimizedImages: Record<string, OptimizedImage> = '
    + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
report = ROOT / '.tmp-improvements/asset-optimization.json'
report.parent.mkdir(parents=True, exist_ok=True)
report.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({'fontsBefore': sum(item['before'] for item in summary['fonts']), 'fontsAfter': sum(item['after'] for item in summary['fonts']), 'images': len(manifest), 'imageSourcesBytes': sum(item['before'] for item in summary['images']), 'largestVariantsBytes': sum(item['largestAfter'] for item in summary['images'])}))
