const fs = require('fs');
const tsx = 'src/app/components/hero/DesktopHomeHero.tsx';
let component = fs.readFileSync(tsx, 'utf8');
const line = component.match(/^\s*<p className="festival-hero__metadata">[^\n]+<\/p>\r?$/m);
if (!line) throw new Error('Hero metadata not found');
component = component.replace(line[0], '').replace('    </section>', '      ' + line[0].trim() + '\n    </section>');
fs.writeFileSync(tsx, component.replace(/\r\n/g, '\n'));
const css = 'src/app/components/hero/DesktopHomeHero.css';
let styles = fs.readFileSync(css, 'utf8');
styles = styles.replace(/\.festival-hero__metadata \{[^}]+\}/, `.festival-hero__metadata {
  position: absolute;
  z-index: 2;
  right: 3.23%;
  bottom: clamp(12px, 1vw, 20px);
  left: 3.23%;
  margin: 0;
  color: #fff;
  font-family: var(--font-editorial-sans);
  font-size: clamp(10px, 0.95vw, 18px);
  font-weight: 400;
  line-height: 1.5;
  letter-spacing: 0.2em;
  word-spacing: 0.5em;
  text-align: center;
  text-wrap: balance;
}`);
styles = styles.replace(/\n\.festival-hero--graphite \.festival-hero__metadata \{[^}]+\}\n/, '\n');
fs.writeFileSync(css, styles.replace(/\r\n/g, '\n'));
console.log('Moved metadata to the bottom of both hero variants; white on graphite.');

