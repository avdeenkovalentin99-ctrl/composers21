import { chromium } from 'playwright';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1672,height:941}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
const cookie=page.getByRole('button',{name:'OK',exact:true});
if(await cookie.isVisible()) await cookie.click();
await page.waitForTimeout(1800);
console.log('desktop', await page.locator('.home-hero-video video').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,paused:v.paused,time:v.currentTime,src:v.currentSrc,filter:getComputedStyle(v).filter,error:v.error?.message})));
await page.screenshot({path:'.tmp-audit/reference-hero-desktop.png'});
await page.locator('.festival-intro-content').scrollIntoViewIfNeeded();
await page.waitForTimeout(5600);
await page.screenshot({path:'.tmp-audit/reference-intro-desktop.png'});
console.log('intro',await page.locator('.festival-intro-reveal').evaluateAll(els=>els.map(el=>({opacity:getComputedStyle(el).opacity,transform:getComputedStyle(el).transform,delay:getComputedStyle(el).transitionDelay,clip:getComputedStyle(el).clipPath}))));
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await page.waitForTimeout(1000);
await page.screenshot({path:'.tmp-audit/reference-hero-mobile.png'});
console.log('mobile',await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,hero:document.querySelector('.reference-hero').getBoundingClientRect().height,src:document.querySelector('video').currentSrc})));
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForTimeout(100);
console.log('reduced',await page.locator('.home-hero-video video').evaluate(v=>({paused:v.paused})));
console.log('errors',errors);
await browser.close();
