import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto('http://127.0.0.1:5176/');
const article=page.locator('.home-media-article').first();
await article.scrollIntoViewIfNeeded();
await page.waitForFunction(()=>document.querySelector('.home-media-article').closest('[data-sync-group]').dataset.syncState==='complete');
const before=await article.boundingBox();
await article.hover();
await page.waitForFunction(()=>getComputedStyle(document.querySelector('.home-media-article > p')).translate==='4px');
assert.deepEqual(await article.boundingBox(),before);
await page.mouse.move(5,5);
await page.waitForFunction(()=>getComputedStyle(document.querySelector('.home-media-article > p')).translate==='none');
await page.emulateMedia({reducedMotion:'reduce'});
await article.hover();
assert.equal(await article.locator('p').first().evaluate(e=>getComputedStyle(e).translate),'none');
console.log('PASS: 4px hover, smooth return, stable dividers, reduced motion');
await browser.close();
