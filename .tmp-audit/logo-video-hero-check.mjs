import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1672,height:941}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/hero2',{waitUntil:'networkidle'});
const cookie=page.getByRole('button',{name:'OK',exact:true});
if(await cookie.isVisible()) await cookie.click();
await page.waitForTimeout(1200);
console.log('hero2',await page.locator('.logo-video-hero video').evaluateAll(vs=>vs.map(v=>({paused:v.paused,time:v.currentTime,filter:getComputedStyle(v).filter,width:v.videoWidth}))));
await page.screenshot({path:'.tmp-audit/logo-video-hero-desktop.png'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'.tmp-audit/logo-video-hero-mobile.png'});
console.log('mobile overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForTimeout(100);
console.log('reduced motion paused',await page.locator('.logo-video-hero video').evaluateAll(vs=>vs.every(v=>v.paused)));
console.log('errors',errors);
await browser.close();