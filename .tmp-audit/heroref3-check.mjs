import { chromium } from 'playwright';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1672,height:941}});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
await page.locator('.festival-hero').waitFor();
await page.evaluate(()=>document.fonts.ready);
const cookie = page.getByRole('button',{name:'OK',exact:true});
if(await cookie.isVisible()) await cookie.click();
await page.waitForTimeout(2000);
console.log(await page.locator('.festival-hero').evaluate(el=>({width:el.clientWidth,title:el.querySelector('h1').getBoundingClientRect().toJSON(),videos:[...el.querySelectorAll('video')].map(v=>({src:v.getAttribute('src'),ready:v.readyState,playing:!v.paused}))})));
await page.screenshot({path:'.tmp-audit/heroref3-first.png'});
await browser.close();
